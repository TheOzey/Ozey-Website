"use client";

import { Alert, Button, FieldError, Input, Label, ListBox, Select, Spinner, TextField } from "@heroui/react";
import { CircleCheck } from "lucide-react";
import Link from "next/link";
import { type FormEvent, useState } from "react";
import { DetailList } from "@/components/data/detail-list";
import { Panel } from "@/components/page/panel";
import {
  ADDRESS_FIELDS,
  type AddressKey,
  type FieldErrors,
  normaliseEmail,
  validateNewEmployee,
} from "@/lib/employees/new-employee";
import { roleLabel } from "@/lib/employees/migrations";

export interface RoleOption {
  /** Stored on the employee; authorization reads it. */
  id: string;
  /** Shown to the user. */
  displayName: string | null;
  description: string | null;
  product: string | null;
  permissions: string[];
}

interface Created {
  employeeNumber: string;
  displayName: string;
  email: string;
  roles: string[];
}

type Values = {
  firstName: string;
  secondName: string;
  lastName: string;
  email: string;
  roles: string[];
  address: Record<AddressKey, string>;
};

const EMPTY: Values = {
  firstName: "",
  secondName: "",
  lastName: "",
  email: "",
  roles: [],
  address: Object.fromEntries(ADDRESS_FIELDS.map((f) => [f.key, ""])) as Record<AddressKey, string>,
};

const FAILURE: Record<number, string> = {
  401: "Your session has ended. Sign in again, then retry.",
  403: "You don't have permission to manage employees.",
  404: "This employee no longer exists.",
  409: "This employee has been deleted and can no longer be edited.",
};

/** What the edit page passes in. Never carries the document id or uid. */
export interface EditTarget {
  employeeNumber: string;
  linked: boolean;
  initial: {
    firstName: string;
    secondName: string;
    lastName: string;
    email: string;
    roles: string[];
    address: Record<string, string>;
  };
}

/**
 * The employee form, for both "Add employee" and "Edit employee". Validation
 * runs inline with the same rules the server applies
 * (lib/employees/new-employee.ts); the server re-validates and is the
 * authority. The employee ID is generated by the server and is never editable.
 */
export function NewEmployeeForm({ roles, edit }: { roles: RoleOption[]; edit?: EditTarget }) {
  const initialValues: Values = edit
    ? {
        firstName: edit.initial.firstName,
        secondName: edit.initial.secondName,
        lastName: edit.initial.lastName,
        email: edit.initial.email,
        roles: edit.initial.roles,
        address: Object.fromEntries(ADDRESS_FIELDS.map((f) => [f.key, edit.initial.address[f.key] ?? ""])) as Record<AddressKey, string>,
      }
    : EMPTY;
  const [values, setValues] = useState<Values>(initialValues);
  const [updated, setUpdated] = useState<{ changed: string[]; reinvited: boolean } | null>(null);
  const [touched, setTouched] = useState<Set<string>>(new Set());
  const [submitted, setSubmitted] = useState(false);
  const [serverErrors, setServerErrors] = useState<FieldErrors>({});
  const [formError, setFormError] = useState<string | null>(null);
  const [submitting, setSubmitting] = useState(false);
  const [created, setCreated] = useState<Created | null>(null);

  const check = validateNewEmployee(values);
  const clientErrors: FieldErrors = check.ok ? {} : check.errors;
  const profileHref = (employeeNumber: string) => `/employees/${encodeURIComponent(employeeNumber)}`;
  const errorFor = (key: keyof FieldErrors) =>
    serverErrors[key] ?? (submitted || touched.has(key) ? clientErrors[key] : undefined);

  const set = (key: keyof FieldErrors, apply: (v: Values) => Values) => {
    setValues(apply);
    if (serverErrors[key]) setServerErrors((e) => Object.fromEntries(Object.entries(e).filter(([k]) => k !== key)));
  };
  const touch = (key: string) => setTouched((t) => new Set(t).add(key));

  async function onSubmit(event: FormEvent) {
    event.preventDefault();
    if (submitting) return;
    setSubmitted(true);
    setFormError(null);
    if (!check.ok) return;
    setSubmitting(true);
    try {
      const res = await fetch(edit ? `/dashboard/api/employees/${encodeURIComponent(edit.employeeNumber)}` : "/dashboard/api/employees", {
        method: edit ? "PATCH" : "POST",
        credentials: "same-origin",
        headers: { "Content-Type": "application/json", Accept: "application/json" },
        body: JSON.stringify(values),
      });
      const body = (await res.json().catch(() => ({}))) as {
        employee?: Created;
        fields?: FieldErrors;
        message?: string;
        changed?: string[];
        reinvited?: boolean;
      };
      if (!edit && res.status === 201 && body.employee) {
        setCreated(body.employee);
        return;
      }
      if (edit && res.status === 200) {
        setUpdated({ changed: body.changed ?? [], reinvited: body.reinvited === true });
        return;
      }
      if (body.fields && Object.keys(body.fields).length > 0) setServerErrors(body.fields);
      else
        setFormError(
          body.message ?? FAILURE[res.status] ?? `The employee could not be ${edit ? "updated" : "created"}. Nothing was saved; try again.`,
        );
    } catch {
      setFormError("The Console could not be reached. Nothing was saved; check your connection and try again.");
    } finally {
      setSubmitting(false);
    }
  }

  if (edit && updated) {
    return (
      <Panel>
        <div className="flex flex-col gap-6" data-state="employee-updated">
          <div className="flex items-start gap-3">
            <CircleCheck className="mt-0.5 size-5 shrink-0 text-success" aria-hidden />
            <div>
              <h2 className="text-base font-semibold text-foreground">
                {updated.changed.length ? "Changes saved" : "No changes to save"}
              </h2>
              <p className="mt-1 text-sm text-muted">
                {updated.changed.length
                  ? `Updated ${edit.employeeNumber}: ${updated.changed.join(", ")}. The change is recorded in the audit log.`
                  : `${edit.employeeNumber} already matched what you submitted.`}
                {updated.reinvited
                  ? " Their Google account was unlinked and their sessions ended; they become active again when they sign in with the new email."
                  : ""}
              </p>
            </div>
          </div>
          <div className="flex flex-wrap gap-2">
            <Link href={profileHref(edit.employeeNumber)} className="button button--primary button--md">
              View profile
            </Link>
            <Link href="/employees" className="button button--primary button--md">
              Back to Employees
            </Link>
          </div>
        </div>
      </Panel>
    );
  }

  if (created) {
    return (
      <Panel>
        <div className="flex flex-col gap-6" data-state="employee-created">
          <div className="flex items-start gap-3">
            <CircleCheck className="mt-0.5 size-5 shrink-0 text-success" aria-hidden />
            <div>
              <h2 className="text-base font-semibold text-foreground">Employee created</h2>
              <p className="mt-1 text-sm text-muted">
                {created.displayName} is invited. They become active the first time they sign in with Google using{" "}
                {created.email}.
              </p>
            </div>
          </div>
          <DetailList
            columns={2}
            items={[
              { label: "Employee ID", value: <span className="font-mono font-semibold">{created.employeeNumber}</span> },
              { label: "Name", value: created.displayName },
              { label: "Email", value: created.email },
              { label: "Role(s)", value: created.roles.map((id) => roleLabel(roles.find((r) => r.id === id) ?? { id })).join(", ") },
            ]}
          />
          <div className="flex flex-wrap gap-2">
            <Link href={profileHref(created.employeeNumber)} className="button button--primary button--md">
              View profile
            </Link>
            <Link href="/employees" className="button button--primary button--md">
              Back to Employees
            </Link>
            <Button
              variant="secondary"
              onPress={() => {
                setCreated(null);
                setValues(EMPTY);
                setTouched(new Set());
                setSubmitted(false);
              }}
            >
              Add another employee
            </Button>
          </div>
        </div>
      </Panel>
    );
  }

  const text = (key: "firstName" | "secondName" | "lastName" | "email", label: string, opts: { required?: boolean; type?: string; autoComplete?: string } = {}) => (
    <TextField
      name={key}
      type={opts.type ?? "text"}
      isRequired={opts.required}
      value={values[key]}
      onChange={(v) => set(key, (s) => ({ ...s, [key]: v }))}
      onBlur={() => {
        touch(key);
        if (key === "email") setValues((s) => ({ ...s, email: normaliseEmail(s.email) }));
      }}
      isInvalid={Boolean(errorFor(key))}
      validationBehavior="aria"
    >
      <Label>
        {label}
        {opts.required ? null : <span className="font-normal text-muted"> (optional)</span>}
      </Label>
      <Input autoComplete={opts.autoComplete} />
      <FieldError>{errorFor(key)}</FieldError>
    </TextField>
  );

  return (
    <form noValidate onSubmit={onSubmit} className="flex flex-col gap-6" aria-busy={submitting}>
      {formError ? (
        <Alert status="danger">
          <Alert.Indicator />
          <Alert.Content>
            <Alert.Description>{formError}</Alert.Description>
          </Alert.Content>
        </Alert>
      ) : null}

      {edit ? (
        <Panel title="Employee ID" description="Assigned when the employee was created. It is permanent and cannot be changed.">
          <span className="font-mono text-sm font-semibold text-foreground" data-field="employee-number">
            {edit.employeeNumber}
          </span>
        </Panel>
      ) : null}

      <Panel title="Personal information" description="The email must be the Google account the employee signs in with.">
        <div className="grid grid-cols-1 gap-5 sm:grid-cols-3">
          {text("firstName", "First name", { required: true, autoComplete: "given-name" })}
          {text("secondName", "Second name", { autoComplete: "additional-name" })}
          {text("lastName", "Last name", { required: true, autoComplete: "family-name" })}
          <div className="sm:col-span-2">
            {text("email", "Email", { required: true, type: "email", autoComplete: "email" })}
            {edit?.linked && normaliseEmail(values.email) !== edit.initial.email ? (
              <p className="mt-2 text-xs text-warning" data-state="email-change-warning">
                This employee has signed in before. Changing the email unlinks their Google account and ends their sessions;
                they must sign in with the new address to become active again.
              </p>
            ) : null}
          </div>
        </div>
      </Panel>

      <Panel title="Role" description="Defines what the employee can access. Roles are managed under Roles.">
        {roles.length === 0 ? (
          <div className="flex flex-col gap-2">
            <Select aria-label="Role" isDisabled placeholder="No roles available">
              <Label>Role</Label>
              <Select.Trigger>
                <Select.Value />
                <Select.Indicator />
              </Select.Trigger>
            </Select>
            <p className="text-sm text-muted" data-state="no-roles">
              A role must first be created under{" "}
              <Link href="/roles" className="text-accent underline-offset-4 hover:underline">
                Roles
              </Link>{" "}
              before an employee can be added.
            </p>
          </div>
        ) : (
          <Select
            name="roles"
            selectionMode="multiple"
            isRequired
            placeholder="Select a role"
            value={values.roles}
            onChange={(keys) => {
              touch("roles");
              set("roles", (s) => ({ ...s, roles: (Array.isArray(keys) ? keys : []).map(String) }));
            }}
            onBlur={() => touch("roles")}
            isInvalid={Boolean(errorFor("roles"))}
            validationBehavior="aria"
            className="max-w-xl"
          >
            <Label>Role</Label>
            <Select.Trigger>
              <Select.Value />
              <Select.Indicator />
            </Select.Trigger>
            <Select.Popover>
              <ListBox selectionMode="multiple">
                {roles.map((r) => (
                  <ListBox.Item key={r.id} id={r.id} textValue={roleLabel(r)}>
                    <div className="flex min-w-0 flex-col">
                      <span className="font-medium">{roleLabel(r)}</span>
                      <span className="truncate text-xs text-muted">
                        {r.description ?? r.permissions.join(", ")}
                      </span>
                    </div>
                    <ListBox.ItemIndicator />
                  </ListBox.Item>
                ))}
              </ListBox>
            </Select.Popover>
            <FieldError>{errorFor("roles")}</FieldError>
          </Select>
        )}
      </Panel>

      <Panel title="Address" description="Optional.">
        <div className="grid grid-cols-1 gap-5 sm:grid-cols-2 lg:grid-cols-3">
          {ADDRESS_FIELDS.map(({ key, label }) => (
            <TextField
              key={key}
              name={key}
              value={values.address[key]}
              onChange={(v) => set(key, (s) => ({ ...s, address: { ...s.address, [key]: v } }))}
              onBlur={() => touch(key)}
              isInvalid={Boolean(errorFor(key))}
              validationBehavior="aria"
            >
              <Label>{label}</Label>
              <Input autoComplete={key === "postalCode" ? "postal-code" : undefined} />
              <FieldError>{errorFor(key)}</FieldError>
            </TextField>
          ))}
        </div>
      </Panel>

      <div className="flex flex-wrap items-center justify-end gap-2">
        <Link href="/employees" className="button button--ghost button--md">
          Cancel
        </Link>
        <Button type="submit" variant="primary" isDisabled={submitting || roles.length === 0} isPending={submitting}>
          {submitting ? <Spinner size="sm" color="current" /> : null}
          {submitting ? (edit ? "Saving…" : "Creating…") : edit ? "Save changes" : "Create employee"}
        </Button>
      </div>
    </form>
  );
}
